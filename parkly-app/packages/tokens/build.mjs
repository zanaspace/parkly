// Builds @parkly/tokens (doc 04 §12): CSS variables, Tailwind preset and a typed
// React Native theme from the DTCG JSON in src/. Run with `pnpm tokens:build`.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import StyleDictionary from 'style-dictionary';

const root = dirname(fileURLToPath(import.meta.url));
const dist = join(root, 'dist');
const PREFIX = 'pk';

const shared = [
  'src/primitive/**/*.json',
  'src/semantic/typography.json',
  'src/semantic/layout.json',
  'src/component/**/*.json',
];

function write(file, content) {
  const path = join(dist, file);
  mkdirSync(dirname(path), { recursive: true });
  writeFileSync(path, content);
}

// --- Theme parity: a key in light must exist in dark and vice versa (doc 07 §6).
function leafPaths(node, prefix = []) {
  if (node && typeof node === 'object' && '$value' in node) return [prefix.join('.')];
  return Object.entries(node)
    .filter(([k]) => !k.startsWith('$'))
    .flatMap(([k, v]) => leafPaths(v, [...prefix, k]));
}
const readJson = (p) => JSON.parse(readFileSync(join(root, p), 'utf8'));
const lightKeys = new Set(leafPaths(readJson('src/semantic/light.json')));
const darkKeys = new Set(leafPaths(readJson('src/semantic/dark.json')));
const mismatched = [...lightKeys]
  .filter((k) => !darkKeys.has(k))
  .concat([...darkKeys].filter((k) => !lightKeys.has(k)));
if (mismatched.length)
  throw new Error(`Theme keys differ between light and dark: ${mismatched.join(', ')}`);

function dictionary(theme, platforms) {
  return new StyleDictionary({
    source: [...shared, `src/semantic/${theme}.json`],
    usesDtcg: true,
    log: { verbosity: 'silent', warnings: 'disabled' },
    platforms,
  });
}

const cssPlatform = (selector, filter) => ({
  css: {
    prefix: PREFIX,
    expand: true,
    transforms: ['name/kebab', 'fontFamily/css', 'cubicBezier/css'],
    files: [
      {
        destination: 'tokens.css',
        format: 'css/variables',
        ...(filter ? { filter } : {}),
        options: { selector, outputReferences: true, showFileHeader: false },
      },
    ],
  },
});

const nativePlatform = {
  native: {
    transforms: [],
    files: [{ destination: 'theme.json', format: 'json/nested' }],
  },
};

// --- CSS: everything on :root (light), theme files re-declared for dark.
const fromDarkFile = (token) => token.filePath.replaceAll('\\', '/').endsWith('semantic/dark.json');
const [lightCss] = await dictionary('light', cssPlatform(':root')).formatPlatform('css');
const [darkCss] = await dictionary(
  'dark',
  cssPlatform('[data-theme="dark"]', fromDarkFile),
).formatPlatform('css');
const darkBody = darkCss.output.slice(
  darkCss.output.indexOf('{') + 1,
  darkCss.output.lastIndexOf('}'),
);

const extras = `
/* Responsive type steps (doc 08 §3.1) */
@media (min-width: 768px) {
  :root {
    --pk-type-display-lg-font-size: 40px; --pk-type-display-lg-line-height: 48px;
    --pk-type-display-md-font-size: 32px; --pk-type-display-md-line-height: 40px;
    --pk-type-heading-xl-font-size: 28px; --pk-type-heading-xl-line-height: 36px;
  }
}
/* Density (doc 08 §3.2, doc 09): attendant PWA = large, admin tables = compact */
[data-density="large"] {
  --pk-space-inset-xs: 8px; --pk-space-inset-sm: 12px; --pk-space-inset-md: 20px;
  --pk-space-stack-xs: 8px; --pk-space-stack-sm: 12px; --pk-space-stack-md: 20px; --pk-space-stack-lg: 32px; --pk-space-stack-xl: 48px;
  --pk-space-inline-xs: 8px; --pk-space-inline-sm: 12px;
  --pk-focus-ring-width: 3px;
}
[data-density="compact"] {
  --pk-space-inset-sm: 6px; --pk-space-inset-md: 12px; --pk-space-inset-lg: 16px; --pk-space-inset-xl: 24px;
  --pk-space-stack-md: 12px; --pk-space-stack-lg: 16px; --pk-space-stack-xl: 32px;
  --pk-space-inline-md: 12px; --pk-space-layout-gutter: 24px; --pk-space-layout-section: 32px;
}
`;

write(
  'css/tokens.css',
  `/* Generated by @parkly/tokens — do not edit. Source: packages/tokens/src */\n${lightCss.output}\n` +
    `[data-theme="dark"] {${darkBody}}\n` +
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {${darkBody}}\n}\n${extras}`,
);

// --- React Native theme: numbers for dimensions, loaded font names per weight.
const RN_FONTS = {
  'Plus Jakarta Sans': {
    600: 'PlusJakartaSans_600SemiBold',
    700: 'PlusJakartaSans_700Bold',
    800: 'PlusJakartaSans_800ExtraBold',
  },
  Inter: {
    400: 'Inter_400Regular',
    500: 'Inter_500Medium',
    600: 'Inter_600SemiBold',
    700: 'Inter_700Bold',
  },
  'JetBrains Mono': { 500: 'JetBrainsMono_500Medium', 600: 'JetBrainsMono_600SemiBold' },
};

const px = (v) => (typeof v === 'string' && /^-?\d+(\.\d+)?px$/.test(v) ? Number.parseFloat(v) : v);
const ms = (v) => (typeof v === 'string' && /^\d+ms$/.test(v) ? Number.parseInt(v, 10) : v);

function nativeType(value, path) {
  const family = Array.isArray(value.fontFamily) ? value.fontFamily[0] : value.fontFamily;
  const fontFamily = RN_FONTS[family]?.[value.fontWeight];
  if (!fontFamily) throw new Error(`No RN font for ${family} ${value.fontWeight} (${path})`);
  const fontSize = px(value.fontSize);
  const em = Number.parseFloat(value.letterSpacing);
  return {
    fontFamily,
    fontSize,
    lineHeight: px(value.lineHeight),
    letterSpacing: Math.round(em * fontSize * 100) / 100,
    ...(path.startsWith('type.price') ? { fontVariant: ['tabular-nums'] } : {}),
  };
}

function toNative(node, path = '') {
  if (Array.isArray(node)) return path.startsWith('font.family') ? node[0] : node;
  if (node && typeof node === 'object') {
    if ('fontFamily' in node && 'fontSize' in node) return nativeType(node, path);
    return Object.fromEntries(
      Object.entries(node).map(([k, v]) => [k, toNative(v, path ? `${path}.${k}` : k)]),
    );
  }
  return ms(px(node));
}

async function nativeTheme(theme) {
  const [file] = await dictionary(theme, nativePlatform).formatPlatform('native');
  return toNative(JSON.parse(file.output));
}

const light = await nativeTheme('light');
const dark = await nativeTheme('dark');

function typeOf(node, indent = '  ') {
  if (Array.isArray(node)) return `readonly ${typeof node[0] === 'number' ? 'number' : 'string'}[]`;
  if (node && typeof node === 'object') {
    const inner = Object.entries(node)
      .map(([k, v]) => `${indent}  ${JSON.stringify(k)}: ${typeOf(v, `${indent}  `)};`)
      .join('\n');
    return `{\n${inner}\n${indent}}`;
  }
  return typeof node === 'number' ? 'number' : 'string';
}

write(
  'native/theme.js',
  `// Generated by @parkly/tokens — do not edit.\nexport const theme = ${JSON.stringify({ light, dark }, null, 2)};\n`,
);
write(
  'native/theme.d.ts',
  `// Generated by @parkly/tokens — do not edit.\nexport type Theme = ${typeOf(light, '')};\nexport declare const theme: { light: Theme; dark: Theme };\n`,
);

// --- Tailwind preset: theme keys point at CSS variables so dark mode needs no `dark:` variants.
const v = (path) => `var(--${PREFIX}-${path.join('-')})`;
function varsFor(node, path) {
  return Object.fromEntries(
    Object.entries(node).map(([k, val]) => [
      k,
      val && typeof val === 'object' && !Array.isArray(val) && !('fontFamily' in val)
        ? varsFor(val, [...path, k])
        : v([...path, k]),
    ]),
  );
}
const flatten = (obj, prefix = '') =>
  Object.entries(obj).reduce((acc, [k, val]) => {
    const key = prefix ? `${prefix}-${k}` : k;
    return typeof val === 'object' ? { ...acc, ...flatten(val, key) } : { ...acc, [key]: val };
  }, {});

const { color, space, radius, shadow, elevation, gradient, z, breakpoint } = light;
const fontSize = Object.fromEntries(
  Object.keys(flatten(varsFor(light.type, ['type']))).map((key) => {
    const base = `--${PREFIX}-type-${key}`;
    return [
      key,
      [
        `var(${base}-font-size)`,
        {
          lineHeight: `var(${base}-line-height)`,
          fontWeight: `var(${base}-font-weight)`,
          letterSpacing: `var(${base}-letter-spacing)`,
        },
      ],
    ];
  }),
);
const preset = {
  theme: {
    extend: {
      backgroundColor: flatten(varsFor(color.bg, ['color', 'bg'])),
      textColor: flatten(varsFor(color.text, ['color', 'text'])),
      borderColor: flatten(varsFor(color.border, ['color', 'border'])),
      colors: Object.fromEntries(
        ['action', 'status', 'verified', 'accent', 'offline', 'focus'].map((g) => [
          g,
          flatten(varsFor(color[g], ['color', g])),
        ]),
      ),
      spacing: Object.fromEntries(
        Object.entries(flatten(varsFor(space, ['space']))).map(([k, val]) => [
          k.replace('_', '.'),
          val,
        ]),
      ),
      borderRadius: flatten(varsFor(radius, ['radius'])),
      boxShadow: {
        ...flatten(varsFor(shadow, ['shadow'])),
        ...flatten(varsFor(elevation, ['elevation'])),
      },
      backgroundImage: flatten(varsFor(gradient, ['gradient'])),
      fontFamily: {
        display: v(['font', 'family', 'display']),
        text: v(['font', 'family', 'text']),
        mono: v(['font', 'family', 'mono']),
      },
      fontSize,
      zIndex: flatten(varsFor(z, ['z'])),
      screens: Object.fromEntries(
        Object.entries(breakpoint)
          .filter(([k]) => k !== 'xs')
          .map(([k, val]) => [k, `${val}px`]),
      ),
    },
  },
};
const presetJson = JSON.stringify(preset, null, 2);
write(
  'tailwind/preset.js',
  `// Generated by @parkly/tokens — do not edit.\nexport default ${presetJson};\n`,
);
write(
  'tailwind/preset.cjs',
  `// Generated by @parkly/tokens — do not edit.\nmodule.exports = ${presetJson};\n`,
);
write(
  'tailwind/preset.d.ts',
  `declare const preset: { theme: { extend: Record<string, unknown> } };\nexport default preset;\n`,
);

// eslint-disable-next-line no-console
console.log('@parkly/tokens built → dist/{css,native,tailwind}');
